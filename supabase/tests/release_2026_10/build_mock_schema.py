def function_source(path: Path, name: str, nth: int = 0) -> str:
    """The nth definition of a function in a file (overloads: nth = 1, 2 ...)."""
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    starts = list(re.finditer(rf"create (?:or replace )?function (?:public\.)?{name}\s*\(", text, re.I))
    if len(starts) <= nth:
        raise SystemExit(f"{name} not found in {path.name}")
    start = starts[nth]
    tag = re.compile(r"\$[A-Za-z_]*\$").search(text, start.end())
    body_close = text.index(tag.group(0), tag.end())
    end = text.index(";", body_close) + 1
    return text[start.start():end]


